/// Diameters of the round icon discs (badges) that sit beside a label.
class BadgeSize {
  BadgeSize._();

  /// Category chips in the transaction form.
  static const sm = 28.0;

  /// Form fields, option tiles, category and list rows.
  static const md = 36.0;

  /// Settings rows, option-sheet rows, transaction rows.
  static const lg = 40.0;
}
